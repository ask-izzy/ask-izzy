// Server only: the lookup table from ISS3 "q" values to the flows which
// produce them. Generated at build time and never sent to the browser.
// See docs/other-services-panel.md § "Turning a related search back into a flow"

import fs from "fs"
import path from "path"
import {z} from "zod"

import type {FlowAnswers} from "@/src/utils/flow-answers"

// The category and personalisation answers which produce an ISS3 "q" value
export type RelatedSearchFlow = {
    category: string,
    answers: FlowAnswers,
}

// Normalised ISS3 "q" values to the flow which produces them
export type RelatedSearchFlows = {[q: string]: RelatedSearchFlow}

// With strict off, zod infers every field as optional, so the parsed result is
// cast to RelatedSearchFlows rather than inferred.
const answerSchema = z.union([z.string(), z.array(z.string())])
const answerOptionsSchema = z.object({
    oneOf: z.array(answerSchema).min(1),
})
const relatedSearchFlowsSchema = z.record(
    z.string(),
    z.object({
        category: z.string(),
        answers: z.record(
            z.string(),
            z.union([answerSchema, answerOptionsSchema]),
        ),
    }),
)

// Makes ISS3 "q" values comparable regardless of case or spacing
export function normaliseIss3Q(q: string): string {
    return q.toLowerCase().replace(/\s+/g, " ").trim()
}

// Written by `yarn generate-related-search-flows`. Read from disk rather than
// bundled so the server bundle stays small and type checking, linting and
// unit tests don't need it to exist.
export const RELATED_SEARCH_FLOWS_PATH = path.join(
    "src",
    "related-searches",
    "related-search-flows.generated.json",
)

// Throws unless the table is the expected shape
export function parseRelatedSearchFlows(table: unknown): RelatedSearchFlows {
    return relatedSearchFlowsSchema.parse(table) as RelatedSearchFlows
}

let flows: RelatedSearchFlows | null = null

/*
 * The generated lookup table, read and checked on first use. Throws if it's
 * missing or the wrong shape (eg generated by another version of the code).
 */
export function getRelatedSearchFlows(): RelatedSearchFlows {
    if (!flows) {
        const json = fs.readFileSync(
            path.join(process.cwd(), RELATED_SEARCH_FLOWS_PATH),
            "utf8",
        )
        flows = parseRelatedSearchFlows(JSON.parse(json))
    }
    return flows
}
